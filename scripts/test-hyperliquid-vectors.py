def check_sdk():
    for name, expected in PACKAGE_VERSIONS.items():
        actual = importlib.metadata.version(name)
        if actual != expected:
            raise RuntimeError(f"{name}: expected {expected}, found {actual}")
    for path, module in (("hyperliquid/utils/signing.py", sdk), ("hyperliquid/utils/types.py", sdk_types)):
        actual = hashlib.sha256(Path(module.__file__).read_bytes()).hexdigest()
        if actual != SOURCE_SHA256[path]:
            raise RuntimeError(f"{path} differs from pinned official SDK commit {SDK_COMMIT}")


def generate():
    check_sdk()
    wallet = RecordingWallet()
    vectors = []
    for network in ("mainnet", "testnet"):
        mainnet = network == "mainnet"
        for name, action in l1_actions():
            for vault in (None, VAULT):
                for expiry in (None, EXPIRY):
                    request = {"action": copy.deepcopy(action), "nonce": NONCE}
                    if vault is not None:
                        request["vaultAddress"] = vault
                    if expiry is not None:
                        request["expiresAfter"] = expiry
                    signature = sdk.sign_l1_action(wallet, request["action"], vault, NONCE, expiry, mainnet)
                    vector = {
                        "name": f"{network}/{name}/{'vault' if vault else 'no-vault'}/{'expiry' if expiry else 'no-expiry'}",
                        "scheme": "l1", "network": network, "signerAddress": wallet.address,
                        "input": request, "digest": wallet.digest(signature),
                        "actionHash": "0x" + sdk.action_hash(action, vault, NONCE, expiry).hex(),
                        "msgpack": "0x" + msgpack.packb(action).hex(),
                        "signature": signature,
                    }
                    vectors.append(vector)
        for name, original, signer in user_actions(wallet.address):
            action = copy.deepcopy(original)
            action["signatureChainId"] = "0x66eee"
            action["hyperliquidChain"] = "Mainnet" if mainnet else "Testnet"
            before = copy.deepcopy(action)
            signature = signer(wallet, action, mainnet)
            assert action == before
            vectors.append({
                "name": f"{network}/{name}", "scheme": "user", "network": network,
                "signerAddress": wallet.address, "input": {"action": action, "nonce": NONCE},
                "digest": wallet.digest(signature), "signature": signature,
            })
    return {
        "schemaVersion": 1,
        "warning": "OFFLINE TEST FIXTURES ONLY. The public upstream test key must never hold assets. All timestamps are intentionally expired. No request was submitted to an exchange.",
        "sdk": {
            "repository": SDK_REPOSITORY, "commit": SDK_COMMIT, "version": PACKAGE_VERSIONS["hyperliquid-python-sdk"],
            "archiveSha256": SDK_ARCHIVE_SHA256, "sourceSha256": SOURCE_SHA256,
            "license": "MIT", "licenseFile": "hyperliquid-sdk-LICENSE.txt",
            "packages": PACKAGE_VERSIONS,
        },
        "testPrivateKey": TEST_PRIVATE_KEY,
        "signerAddress": wallet.address,
        "vectors": vectors,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="replace only the checked-in offline fixture JSON")
    args = parser.parse_args()
    result = generate()
    encoded = json.dumps(result, indent=2, ensure_ascii=True) + "\n"
    if args.write:
        FIXTURE_PATH.parent.mkdir(parents=True, exist_ok=True)
        FIXTURE_PATH.write_text(encoded, encoding="utf-8")
        print(f"Wrote {len(result['vectors'])} offline official-SDK vectors")
    elif not FIXTURE_PATH.exists() or FIXTURE_PATH.read_text(encoding="utf-8") != encoded:
        raise SystemExit("Fixture mismatch; inspect the pinned SDK and regenerate with --write")
    else:
        print(f"Verified {len(result['vectors'])} offline official-SDK vectors")


if __name__ == "__main__":
    main()
