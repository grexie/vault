class RecordingWallet:
    """Record the exact SignableMessage passed by the upstream signing code."""

    def __init__(self):
        self.wallet = Account.from_key(TEST_PRIVATE_KEY)
        self.message = None
        self.signed_message = None

    @property
    def address(self):
        return self.wallet.address

    def sign_message(self, message):
        self.message = message
        self.signed_message = self.wallet.sign_message(message)
        return self.signed_message

    def digest(self, signature):
        # EIP-191 framing of the message generated by the SDK's encode_typed_data.
        value = keccak(b"\x19" + self.message.version + self.message.header + self.message.body)
        assert value == self.signed_message.message_hash
        recovered = Account.recover_message(
            self.message, vrs=(signature["v"], signature["r"], signature["s"])
        )
        assert recovered == self.address
        return "0x" + value.hex()


def wire_order(*, trigger=False, cloid=False):
    order = {
        "coin": "fixture",
        "is_buy": not trigger,
        "sz": 1.25,
        "limit_px": 2500.125,
        "reduce_only": trigger,
        "order_type": (
            {"trigger": {"triggerPx": 2400.5, "isMarket": True, "tpsl": "sl"}}
            if trigger else {"limit": {"tif": "Gtc"}}
        ),
    }
    if cloid:
        order["cloid"] = sdk_types.Cloid.from_str(CLOID)
    return sdk.order_request_to_order_wire(order, 4)


